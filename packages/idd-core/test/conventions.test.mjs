import assert from "node:assert/strict";
import { test } from "node:test";

import { parseRepos } from "../src/config/areas.ts";
import { isAiMarkLine, sectionOf, withoutAiMarks } from "../src/config/conventions.ts";

const POINT = { commit: { file: "RULES.md", section: "## Commit" } };

test("the pointers are read beside the areas, a commit form may take its source from its pointer, and naming one rule twice is a config error", () => {
  const text = (extra) => JSON.stringify({ repos: { "o/r": { upstream: "/u", work: "/w", ...extra } } });
  const file = parseRepos(text({ conventions: { ...POINT, pr: { file: ".agents/skills/create-pr/SKILL.md", section: "## PR本文テンプレート" } }, commit_convention: { types: ["feat", "fix"] } }));
  assert.deepEqual(file.conventions["o/r"].commit, { file: "RULES.md", section: "## Commit" });
  assert.equal(file.commitConvention["o/r"].source, "RULES.md の ## Commit");
  // the settings that saved submits are hashed from do not move with the pointers
  assert.deepEqual(parseRepos(text({})).areas["o/r"], file.areas["o/r"]);
  assert.equal(parseRepos(text({})).conventions, undefined);
  // the same rule named in two places
  assert.throws(() => parseRepos(text({ conventions: POINT, commit_convention: { types: ["feat"], source: "RULES.md の ## Commit" } })), /commit_convention\.source.*conventions\.commit/);
  // without a pointer the source is still needed
  assert.throws(() => parseRepos(text({ commit_convention: { types: ["feat"] } })), /source/);
  for (const bad of [
    "x", { review: { file: "a.md", section: "## a" } }, { commit: "RULES.md" }, { commit: { file: "RULES.md" } },
    { commit: { file: "RULES.md", section: "Commit" } }, { commit: { file: "/etc/passwd", section: "## a" } },
    { commit: { file: "../x.md", section: "## a" } }, { commit: { file: "a.md", section: "## a", extra: 1 } },
  ]) assert.throws(() => parseRepos(text({ conventions: bad })), /conventions/, JSON.stringify(bad));
});

test("a section runs from its heading to the next heading of its level or above, a fenced line is no heading, and the AI's marks are taken out", () => {
  const text = "# T\n\n## A\n\na1\n\n```md\n## not a heading\n```\n\n### A.1\n\na2\n\n## B\n\nb1\n";
  for (const [heading, want] of [["## A", "## A\n\na1\n\n```md\n## not a heading\n```\n\n### A.1\n\na2"], ["### A.1", "### A.1\n\na2"], ["## B", "## B\n\nb1"], ["## C", null], ["# A", null]]) {
    assert.equal(sectionOf(text, heading), want, `${heading} (the depth is part of the heading)`);
  }
  // a heading in an HTML comment neither starts nor ends a section, and a comment after a heading is not in its name
  const commented = "## A\n\na1\n<!--\n## B\n-->\na2 <!-- ## C --> a3\n\n## D <!-- note -->\n\nd1\n";
  for (const [heading, want] of [["## A", "## A\n\na1\n<!--\n## B\n-->\na2 <!-- ## C --> a3"], ["## B", null], ["## D", "## D <!-- note -->\n\nd1"]]) assert.equal(sectionOf(commented, heading), want, heading);
  assert.equal(withoutAiMarks("## 概要\n\n🤖 AIが作成したPR本文です。削除してください。\n\n- 変更点\nCo-Authored-By: x <x@y>"), "## 概要\n\n\n- 変更点");
  // the forms the PR draft refuses are not shown to the writer either, and the headings and other sentences stay
  assert.equal(withoutAiMarks("## 概要\n\nGenerated with Claude Code\n> 🤖 Generated by a tool\n* generated with x\n- 変更点\nco-authored-by : y"), "## 概要\n\n- 変更点");
  assert.equal(withoutAiMarks("## Generated with care\n\nThis was generated with a script."), "## Generated with care\n\nThis was generated with a script.");
});

test("a section is cut as CommonMark reads it: code spans, fences of other lengths and kinds, and a comment that never closes", () => {
  const cut = (text, heading = "## A") => sectionOf(text, heading);
  // a `<!--` in an inline code span opens nothing, so the heading after it still ends the section
  assert.equal(cut("## A\n\nuse `<!--` to open\n\n## B\n\nb\n"), "## A\n\nuse `<!--` to open");
  // a fence is closed only by a fence of its character at least as long: a shorter one or another kind is its content
  assert.equal(cut("## A\n\n````md\n```\n## x\n```\n````\n\n## B\n"), "## A\n\n````md\n```\n## x\n```\n````");
  assert.equal(cut("## A\n\n```md\n~~~\n## x\n~~~\n```\n\n## B\n"), "## A\n\n```md\n~~~\n## x\n~~~\n```");
  assert.equal(cut("## A\n\n~~~\n```\n## x\n~~~\n\n## B\n"), "## A\n\n~~~\n```\n## x\n~~~");
  // nothing in a fence opens or closes a comment
  assert.equal(cut("## A\n\n```\n<!-- never closed\n```\n\n## B\n"), "## A\n\n```\n<!-- never closed\n```");
  assert.equal(cut("## A\n\n<!--\n```\n-->\n\ntext\n\n## B\n"), "## A\n\n<!--\n```\n-->\n\ntext");
  // a `<!--` in the middle of a line with no `-->` after it is text, not a comment to the end of the file
  assert.equal(cut("## A\n\nsee <!-- here\n\n## B\n\nb\n"), "## A\n\nsee <!-- here");
  assert.equal(cut("## A\n\nsee <!-- here\n\n## B\n\nb\n", "## B"), "## B\n\nb");
  // a backtick fence's info string has no backtick: such a line is no fence
  assert.equal(cut("## A\n\n``` `x`\n\n## B\n"), "## A\n\n``` `x`");
});

test("a line is an AI's mark by one test shared with the PR draft's check", () => {
  for (const l of ["🤖 AIが作成したPR本文です。", "🤖 anything", "  > Co-Authored-By: a <a@b>", "Generated with Claude Code", "本文の AIが作成した 印"]) assert.equal(isAiMarkLine(l), true, l);
  for (const l of ["## Generated with care", "This was generated with a script.", "### 概要"]) assert.equal(isAiMarkLine(l), false, l);
});
